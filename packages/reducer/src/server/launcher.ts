import type { Launcher } from '../launcher/types.js'
import { spawn, spawnSync } from 'node:child_process'
import { mkdirSync, openSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { basename, join } from 'pathe'
import { killProcess, listProcesses } from '../launcher/process.js'
import { hashName } from '../theme.js'

/**
 * @file Start / find / stop the dedicated server of a pack.
 *
 * A {@link Launcher} like any other, so `restart`, `ready`, `kill` and the
 * binary search work on the server without knowing what they are driving. Two
 * things make it different from the client launchers: the JVM is started here
 * rather than handed to a launcher app, and the process must be recognisable
 * afterwards — a stamped system property identifies exactly this game dir, so a
 * server started from another pack (or the client itself) is never touched.
 */

/** The console window's own copy of the command, so it can be re-run by hand. */
const RUN_SCRIPT = 'run.ps1'

export interface ServerLaunchSpec {
  gameDir  : string
  java     : string
  /** Jar handed to `java -jar`. */
  serverJar: string
  jvmArgs  : string[]
  minRam   : string
  maxRam   : string
  /** Give the JVM its own console window, so `stop` and `op` can be typed. */
  console  : boolean
  /** Console window title — the pack this server belongs to. */
  title    : string
}

/** PowerShell 7 if it is installed, else the one Windows ships. */
function powershellBinary(): string {
  const { error } = spawnSync('pwsh', ['-NoLogo', '-NoProfile', '-Command', 'exit 0'])
  return error ? 'powershell' : 'pwsh'
}

export class ServerLauncher implements Launcher {
  readonly name = 'server'
  /** Stamped on the JVM so `getPid` can recognise this game dir with certainty. */
  private readonly marker: string

  constructor(private readonly spec: ServerLaunchSpec) {
    this.marker = `-Dmctools.reducer.server=${hashName(spec.gameDir).toString(16).padStart(8, '0')}`
  }

  /** Full JVM command line, in launch order. */
  args(): string[] {
    return [
      `-Xms${this.spec.minRam}`,
      `-Xmx${this.spec.maxRam}`,
      ...this.spec.jvmArgs,
      this.marker,
      '-jar',
      basename(this.spec.serverJar),
      'nogui',
    ]
  }

  async describe(): Promise<string> {
    return `${basename(this.spec.serverJar)} · ${this.spec.minRam}-${this.spec.maxRam} · ${this.spec.gameDir}`
  }

  async getPid(): Promise<number | null> {
    const names = process.platform === 'win32' ? ['java.exe', 'javaw.exe'] : ['java']
    for (const exe of names) {
      for (const proc of await listProcesses(exe)) {
        if (proc.cmd.includes(this.marker)) return proc.pid
      }
    }
    return null
  }

  async launch(): Promise<void> {
    const { gameDir, java, console: wantsConsole } = this.spec
    if (!this.spec.serverJar) {
      throw new Error('no server jar to boot — set "server.jar" (and "server.install") in reducer.config.yml')
    }
    mkdirSync(join(gameDir, 'logs'), { recursive: true })
    if (wantsConsole && process.platform === 'win32') return this.openConsole()

    // Headless: the JVM keeps running after this process returns, and its
    // console output lands next to the logs the monitor already reads.
    const out = openSync(join(gameDir, 'logs', 'server-console.log'), 'a')
    spawn(java, this.args(), { cwd: gameDir, detached: true, stdio: ['ignore', out, out] }).unref()
  }

  /**
   * Give the server a console of its own.
   *
   * A dedicated server without a live console is half a server — `stop`, `op`
   * and every other command are typed there — and the terminal that started it
   * is usually needed for something else a minute later. So the JVM gets its
   * own window and this process returns.
   *
   * The window lives exactly as long as the JVM: no `-NoExit`, so a `stop`
   * typed there (or `reducer kill --server`) takes the console with it and a
   * day of restarts leaves no dead windows behind. What the server printed is
   * in `logs/`; {@link RUN_SCRIPT} re-runs the very same command by hand.
   */
  private openConsole(): void {
    const { gameDir, java } = this.spec
    const quote = (arg: string) => `'${arg.replace(/'/g, '\'\'')}'`
    writeFileSync(join(gameDir, RUN_SCRIPT), [
      '# Generated by @mctools/reducer — rewritten on every launch.',
      `$Host.UI.RawUI.WindowTitle = ${quote(this.spec.title)}`,
      'Set-Location -LiteralPath $PSScriptRoot',
      '$jvmArgs = @(',
      ...this.args().map(arg => `  ${quote(arg)}`),
      ')',
      `& ${quote(java)} @jvmArgs`,
      '',
    ].join('\n'))

    spawn('cmd', [
      '/c',
      'start',
      this.spec.title,
      powershellBinary(),
      '-NoLogo',
      '-ExecutionPolicy',
      'Bypass',
      '-File',
      RUN_SCRIPT,
    ], { cwd: gameDir, detached: true, stdio: 'ignore' }).unref()
  }

  async kill(pid: number): Promise<void> {
    await killProcess(pid)
  }
}
